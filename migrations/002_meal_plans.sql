-- Run after the application's pacientes and nutricionistas tables exist.
CREATE TABLE IF NOT EXISTS dieta (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id integer NOT NULL REFERENCES pacientes(id),
    nutricionista_id integer NOT NULL REFERENCES nutricionistas(id)
);

CREATE TABLE IF NOT EXISTS refeicao (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dieta_id integer NOT NULL REFERENCES dieta(id) ON DELETE CASCADE,
    periodo text NOT NULL,
    descricao text NOT NULL
);

ALTER TABLE refeicao
    ADD COLUMN IF NOT EXISTS horario time,
    ADD COLUMN IF NOT EXISTS pedido_id uuid,
    ADD COLUMN IF NOT EXISTS observacao text;

CREATE UNIQUE INDEX IF NOT EXISTS refeicao_pedido_id_idx ON refeicao(pedido_id);

CREATE TABLE IF NOT EXISTS refeicao_alimento (
    refeicao_id integer NOT NULL REFERENCES refeicao(id) ON DELETE CASCADE,
    ordem integer NOT NULL,
    taco_id integer NOT NULL,
    nome text NOT NULL,
    medida text NOT NULL,
    quantidade numeric NOT NULL CHECK (quantidade > 0),
    peso_gramas numeric NOT NULL CHECK (peso_gramas > 0),
    PRIMARY KEY (refeicao_id, ordem)
);
